import { copyFileSync, constants, mkdirSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { visualReferencePath } from '../src/shared/visual-reference-path.mjs';
const args = process.argv.slice(2);
const value = name => args[args.indexOf(name) + 1];
if (!args.includes('--source') || !args.includes('--prompt')) throw new Error('Usage: node scripts/save-visual-reference.mjs --source <image.png> --prompt <number> [--annotation]');
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const source = value('--source');
const target = join(root, 'visual_ref', visualReferencePath(basename(source), Number(value('--prompt')), args.includes('--annotation')));
mkdirSync(dirname(target), {recursive:true});
copyFileSync(source, target, constants.COPYFILE_EXCL);
console.log(target);
